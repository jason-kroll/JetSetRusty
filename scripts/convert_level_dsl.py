#!/usr/bin/env python3
"""Convert one src/levels.rs room from the flattened LevelData literal to the
level! DSL (the macro at the top of src/levels.rs).

LEVEL_DATA's flattened literals were generated by scripts/convert_levels.py
from the C original's levelData table; this is the second hop of the same
provenance chain: flattened literal -> level! invocation. Committed for the
record and for the room-by-room conversions; never invoked by CI, build.rs,
or the test suite. The emitted block is a pure function of the parsed
literal, so the same literal always converts to the same text.

Verification is layered, so a broken conversion cannot print or write:
  1. the literal only parses under shape assertions (512 cells at 0..9,
     four exits, ten slots, ten 8-byte sprites, a padded item list whose
     count matches and has no holes);
  2. the emitted block is re-parsed and every field is compared against
     the literal it replaces;
  3. if reference/c-original is present, the same fields are compared
     against the C original's entry for the room's title -- the
     transcription this port must preserve. C lists fewer legends and
     sprites than it has slots (the tail is zero-filled), so the explicit
     prefix compares and the Rust literal's padding is asserted to be
     exactly that zero fill (Space legends, GFX_SPACE sprites).

usage:
  python3 scripts/convert_level_dsl.py --scan         readiness of all rooms
  python3 scripts/convert_level_dsl.py 28             print level 28's block
  python3 scripts/convert_level_dsl.py --write 28     replace it in place
  (after --write: cargo fmt, cargo test)
"""

import argparse
import re
import sys
from pathlib import Path

ROOMS = 60
COLS = 32
ROWS = 16
CELLS = ROWS * COLS
SLOTS = 10
ITEM_CAP = 12

# game.h's T_* tile type names -> levels.rs TileType variants
T_TYPE = {
    "SPACE": "Space",
    "ITEM": "Item",
    "SOLID": "Solid",
    "FLOOR": "Floor",
    "SOLIDFLOOR": "SolidFloor",
    "CONVEYL": "ConveyL",
    "CONVEYR": "ConveyR",
    "RAMPL": "RampL",
    "RAMPR": "RampR",
    "RAMPLC": "RampLC",
    "RAMPRC": "RampRC",
    "HARM": "Harm",
}


class ConvertError(Exception):
    pass


def assert_(cond, message):
    if not cond:
        raise ConvertError(message)


def attr_value(text):
    return int(text, 16) if text.lower().startswith("0x") else int(text)


def split_sprites(section):
    """Top-level entries of a gfx array: GFX_SPACE or a byte list."""
    entries, depth, cur = [], 0, ""
    for ch in section:
        if ch == "[":
            depth += 1
        if ch == "]":
            depth -= 1
        if ch == "," and depth == 0:
            if cur.strip():
                entries.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        entries.append(cur.strip())
    return entries


# ---- block bounds ----------------------------------------------------------------


def block_bounds(src, level):
    """Line bounds of room `level`: its marker comment through the line
    before the next marker (or the array's closing bracket)."""
    markers = list(re.finditer(r"// Level (\d+):", src))
    assert_(len(markers) == ROOMS, f"expected 60 rooms, found {len(markers)}")
    assert_(int(markers[level].group(1)) == level, f"room markers out of order at {level}")
    start = src.rindex("\n", 0, markers[level].start()) + 1
    if level + 1 < ROOMS:
        end = src.rindex("\n", 0, markers[level + 1].start()) + 1
    else:
        end = src.index("\n];", start) + 1
    return start, end


# ---- the flattened literal -------------------------------------------------------


def parse_literal(block, level):
    """One ```// Level N: ...``` block -> fields, or ConvertError."""
    comment = block.splitlines()[0]
    assert_(comment.lstrip().startswith("// Level "), f"room {level}: missing marker comment")
    assert_("level! {" not in block, f"room {level} is already in DSL form")

    def find(pattern, what):
        m = re.search(pattern, block, re.S)
        assert_(m, f"room {level}: no {what} in literal")
        return m

    title = find(r'title: "([^"]*)"', "title").group(1)
    assert_(title, f"room {level}: empty title")

    exits = [int(x) for x in find(r"map: \[([^\]]*)\]", "map").group(1).split(",")]
    assert_(len(exits) == 4, f"room {level}: map has {len(exits)} exits, want 4")

    data = [
        int(x)
        for x in find(r"data: \[(.*?)\n        \]", "data grid").group(1).split(",")
        if x.strip()
    ]
    assert_(len(data) == CELLS, f"room {level}: {len(data)} cells, want {CELLS}")
    bad = [v for v in data if not 0 <= v <= 9]
    assert_(not bad, f"room {level}: grid values outside the glyph range 0..9: {bad[:4]}")

    sprites = []
    for entry in split_sprites(find(r"gfx: \[(.*?)\n        \]", "gfx").group(1)):
        if entry == "GFX_SPACE":
            sprites.append([0] * 8)
        else:
            assert_(entry.startswith("[") and entry.endswith("]"),
                    f"room {level}: unknown sprite constant {entry!r}")
            bytes_ = [int(x) for x in entry.strip("[] ").split(",")]
            assert_(len(bytes_) == 8, f"room {level}: sprite has {len(bytes_)} bytes, want 8")
            sprites.append(bytes_)
    assert_(len(sprites) == SLOTS, f"room {level}: {len(sprites)} sprites, want {SLOTS}")

    info = re.findall(
        r"attr: (0x[0-9A-Fa-f]+|\d+),\s*tile_type: TileType::(\w+)", block
    )
    assert_(len(info) == SLOTS, f"room {level}: {len(info)} tile legends, want {SLOTS}")
    # (source text kept for emit, value for comparison)
    info = [(text, attr_value(text), kind) for text, kind in info]

    count = int(find(r"item_count: (\d+)", "item_count").group(1))
    items = [int(x) for x in find(r"item: \[([^\]]*)\]", "items").group(1).split(",")]
    assert_(len(items) == ITEM_CAP, f"room {level}: {len(items)} item slots, want {ITEM_CAP}")
    assert_(0 <= count <= ITEM_CAP, f"room {level}: item_count {count} out of range")
    assert_(all(v != 0 for v in items[:count]), f"room {level}: zero inside the item list")
    assert_(all(v == 0 for v in items[count:]), f"room {level}: item padding is not zero")

    return {
        "level": level,
        "comment": comment,
        "title": title,
        "exits": exits,
        "data": data,
        "sprites": sprites,
        "info": info,
        "count": count,
        "items": items,
    }


def normalized(fields):
    """Fields as comparable values (attrs as ints, sprites as byte lists)."""
    return {
        "title": fields["title"],
        "exits": list(fields["exits"]),
        "data": list(fields["data"]),
        "info": [(v, k) for _, v, k in fields["info"]],
        "sprites": fields["sprites"],
        "count": fields["count"],
        "items": list(fields["items"][: fields["count"]]),
    }


# ---- emit ------------------------------------------------------------------------


def to_dsl(fields):
    rows = [
        "".join("." if v == 0 else str(v) for v in fields["data"][r * COLS : (r + 1) * COLS])
        for r in range(ROWS)
    ]
    kinds = [k for _, _, k in fields["info"]]
    kind_w = max([len(k) for k in kinds] + [7])
    attr_w = max([len(a) for a, _, _ in fields["info"]] + [5])
    exits = ", ".join(
        f"{name}: {'none' if fields['exits'][n] == 0 else fields['exits'][n]}"
        for n, name in enumerate(("above", "right", "below", "left"))
    )
    lines = [fields["comment"], "    level! {",
             f'        title: "{fields["title"]}",',
             f"        exits {{ {exits} }},"]
    lines.append("        tiles {")
    for slot, (attr, _, kind) in enumerate(fields["info"]):
        lines.append(f"            {slot}: {kind:<{kind_w}} attr {attr:<{attr_w}} gfx {sprite_text(fields['sprites'][slot])};")
    lines.append("        },")
    lines.append("        grid {")
    lines += [f'            "{row}",' for row in rows]
    lines.append("        },")
    items = ", ".join(str(v) for v in fields["items"][: fields["count"]])
    lines.append(f"        items [{items}],")
    lines.append("    },")
    return "\n".join(lines)


def sprite_text(sprite):
    return "*" if sprite == [0] * 8 else "[" + ", ".join(str(b) for b in sprite) + "]"


def parse_dsl(text, level):
    """An emitted level! block -> fields in normalized() shape."""
    def find(pattern, what):
        m = re.search(pattern, text, re.S)
        assert_(m, f"room {level}: emitted block has no {what}")
        return m

    title = find(r'title: "([^"]*)"', "title").group(1)
    exits = [
        0 if x == "none" else int(x)
        for x in find(
            r"exits \{ above: (\S+), right: (\S+), below: (\S+), left: (\S+) \}",
            "exits",
        ).groups()
    ]
    rows = re.findall(r'"([^"]*)"', find(r"grid \{(.*?)\},", "grid").group(1))
    assert_(len(rows) == ROWS, f"room {level}: grid has {len(rows)} rows, want {ROWS}")
    assert_(all(len(r) == COLS for r in rows), f"room {level}: a grid row is not {COLS} cells")
    data = [0 if ch == "." else int(ch) for row in rows for ch in row]

    pairs = re.findall(r"(\d+): (\w+)\s+attr (\S+)\s+gfx (.*?);", text)
    assert_(len(pairs) == SLOTS, f"room {level}: {len(pairs)} tile legends, want {SLOTS}")
    info = [(attr_value(a), k) for _, k, a, _ in pairs]
    sprites = [
        [0] * 8 if s == "*" else [int(x) for x in s.strip("[] ").split(",")]
        for _, _, _, s in pairs
    ]

    items = [
        int(x) for x in find(r"items \[([^\]]*)\]", "items").group(1).split(",") if x.strip()
    ]
    assert_(len(items) <= ITEM_CAP, f"room {level}: more than {ITEM_CAP} items")

    return {
        "title": title,
        "exits": exits,
        "data": data,
        "info": info,
        "sprites": sprites,
        "count": len(items),
        "items": items,
    }


def compare(name, want, got, errors):
    if want != got:
        errors.append(f"{name}: emitted {got!r} != literal {want!r}")


# ---- the C original ----------------------------------------------------------------


def c_reference(csrc, title, level):
    i = csrc.index(f'.title = "{title}"')
    tail = csrc.index(".title =", i + 10) if ".title =" in csrc[i + 10 :] else len(csrc)
    block = csrc[i:tail]
    assert_(".data" in block, f"room {level}: C block for {title!r} looks truncated")

    exits = [int(x) for x in re.search(r"\.map = \{([^}]*)\}", block).group(1).split(",")]
    data = [
        int(x)
        for x in re.search(r"\.data = \{(.*?)\},", block, re.S).group(1).split(",")
        if x.strip()
    ]
    assert_(len(data) == CELLS, f"room {level}: C data has {len(data)} cells")
    assert_(all(0 <= v <= 9 for v in data), f"room {level}: C grid value outside 0..9")

    gfx_section = re.search(r"\.gfx = \{(.*?)\n        \},", block, re.S).group(1)
    sprites = []
    for entry in [e.strip().rstrip(",") for e in gfx_section.strip().split("\n") if e.strip()]:
        if entry == "SPACE":
            sprites.append([0] * 8)
        else:
            assert_(entry.startswith("{") and entry.endswith("}"),
                    f"room {level}: unknown C sprite {entry!r}")
            sprites.append([int(x) for x in entry.strip("{} ").split(",")])
    assert_(len(sprites) <= SLOTS, f"room {level}: C room has {len(sprites)} sprites, want at most {SLOTS}")

    info = re.findall(r"\{(0x[0-9A-Fa-f]+|\d+),\s*T_(\w+)\}", block)
    items = [int(x) for x in re.search(r"\.item = \{([^}]*)\}", block).group(1).split(",") if x.strip()]

    return {
        "exits": exits,
        "data": data,
        "sprites": sprites,
        "info": [(attr_value(a), T_TYPE[t]) for a, t in info],
        "items": items,
    }


def c_cross_check(fields, c, level, errors):
    """Compare the Rust literal against the C original. C stops at the last
    explicit legend/sprite, implying zero fill; the Rust literal spells
    that out, so the explicit prefix compares and the padding is asserted
    to be exactly that zero fill."""
    want = normalized(fields)
    if want["exits"] != c["exits"]:
        errors.append(f"exits: literal {want['exits']} != C {c['exits']}")
    if want["data"] != c["data"]:
        diff = sum(a != b for a, b in zip(want["data"], c["data"]))
        errors.append(f"grid: {diff} of {CELLS} cells differ from C")

    n = len(c["sprites"])
    if want["sprites"][:n] != c["sprites"]:
        errors.append(f"sprites: literal {want['sprites'][:n]} != C {c['sprites']}")
    unfilled = [k for k in range(n, SLOTS) if want["sprites"][k] != [0] * 8]
    if unfilled:
        errors.append(f"C lists {n} sprites; Rust slots {unfilled} are not zero-fill")

    n = len(c["info"])
    if want["info"][:n] != c["info"]:
        errors.append(f"tile legends: literal {want['info'][:n]} != C {c['info']}")
    unfilled = [k for k in range(n, SLOTS) if want["info"][k] != (0, "Space")]
    if unfilled:
        errors.append(f"C lists {n} legends; Rust slots {unfilled} are not zero-fill")

    if want["items"] != c["items"][: len(want["items"])]:
        errors.append(f"items: literal {want['items']} != C {c['items'][:len(want['items'])]}")


# ---- driver --------------------------------------------------------------------------


def convert(src, level, errors):
    """The full pipeline minus the splice and the C check:
    literal -> DSL, re-parsed and compared field by field."""
    start, end = block_bounds(src, level)
    fields = parse_literal(src[start:end], level)
    dsl = to_dsl(fields)
    got = parse_dsl(dsl, level)
    want = normalized(fields)
    for key in want:
        compare(key, want[key], got[key], errors)
    return fields, dsl


def main():
    ap = argparse.ArgumentParser(description="level! DSL converter for src/levels.rs")
    ap.add_argument("level", nargs="?", type=int, help="room number, 0..59")
    ap.add_argument("--write", action="store_true", help="replace the literal in src/levels.rs")
    ap.add_argument("--scan", action="store_true", help="report the readiness of all 60 rooms")
    ap.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent.parent,
                    help="repo root (default: this script's repo)")
    args = ap.parse_args()

    if not args.scan and args.level is None:
        ap.error("give a room number, or --scan")

    levels_path = args.repo / "src" / "levels.rs"
    src = levels_path.read_text()

    if args.scan:
        status = 0
        for level in range(ROOMS):
            try:
                start, end = block_bounds(src, level)
                block = src[start:end]
                if "level! {" in block:
                    got = parse_dsl(block, level)
                    print(f"room {level:2}: already DSL ({got['count']} items)")
                    continue
                errors = []
                fields, _ = convert(src, level, errors)
                if errors:
                    raise ConvertError("; ".join(errors))
                print(f"room {level:2}: convertible ({fields['title']}, {fields['count']} items)")
            except (ConvertError, ValueError) as e:
                status = 1
                print(f"room {level:2}: NOT convertible: {e}")
        sys.exit(status)

    assert_(0 <= args.level < ROOMS, f"room number must be 0..{ROOMS - 1}")
    errors = []
    try:
        fields, dsl = convert(src, args.level, errors)
        cpath = args.repo / "reference" / "c-original" / "src" / "levels.c"
        if cpath.exists():
            c_cross_check(fields, c_reference(cpath.read_text(), fields["title"], args.level),
                           args.level, errors)
        else:
            print("warning: reference/c-original not found, C cross-check skipped")
    except (ConvertError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        sys.exit(1)

    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        sys.exit(1)

    if args.write:
        start, end = block_bounds(src, args.level)
        out = src[:start] + dsl + "\n" + src[end:]
        levels_path.write_text(out)
        nstart, nend = block_bounds(out, args.level)
        wrote = parse_dsl(out[nstart:nend], args.level)
        if wrote != normalized(fields):
            print("error: written block did not re-read as the same room", file=sys.stderr)
            sys.exit(1)
        print(f"room {args.level}: converted in place, verified; run cargo fmt and cargo test")
    else:
        print(dsl)


if __name__ == "__main__":
    main()
