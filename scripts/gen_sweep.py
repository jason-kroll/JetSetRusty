#!/usr/bin/env python3
"""Generate tests/scenarios/sweep-NN.txt: one fuzz scenario per level (0-59).

Deterministic: fixed seed, explicit output lines. The generated .txt files are
committed and are what the tests run — this script is documentation only,
never invoked by CI, build.rs, or the test suite. Re-running it must produce
byte-identical files.
"""
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "tests" / "scenarios"
SEED = 20261117
FRAMES = 500
KEYS = ["left", "right", "space"]

def main():
    for level in range(0, 60):
        rng = random.Random(SEED + level)
        lines = [
            f"# Room-sweep fuzz: level {level} (see ROOMS.md), seeded random input.",
            "# Generated by scripts/gen_sweep.py — do not edit by hand.",
            f"frames {FRAMES}",
            f"seed {level}",
            "100 space          # skip the code card",
            "300 enter          # start the game (The Bathroom, level 33)",
            f"340 set level {level}   # enter room {level} from the left edge",
            "360 set lives 9    # deaths respawn instead of game-over",
        ]
        for f in range(400, FRAMES):
            if rng.random() < 0.6:
                lines.append(f"{f} {rng.choice(KEYS)} {rng.randint(1, 8)}")
        path = OUT / f"sweep-{level:02}.txt"
        path.write_text("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
